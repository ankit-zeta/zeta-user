export const seedAll = mutation({
  args: { token: v.string() },
  handler: async (ctx, args) => {
    // Require admin role
    const session = await ctx.db
      .query("sessions")
      .withIndex("by_token", (q) => q.eq("token", args.token))
      .first();
    if (!session || session.expiresAt < Date.now()) {
      throw new Error("Unauthorized: Invalid session");
    }
    const user = await ctx.db.get(session.userId);
    if (!user || !["super_admin", "admin"].includes((user as any).role)) {
      throw new Error("Forbidden: Admin privileges required");
    }

    // Look up program IDs by slug
    const programIds: Record<string, any> = {};
    for (const [key, slug] of Object.entries(PLAN_SLUGS)) {
      const prog = await ctx.db
        .query("programs")
        .withIndex("by_slug", (q) => q.eq("slug", slug))
        .first();
      if (prog) programIds[key] = prog._id;
    }

    // Check for existing jobs to avoid duplicates
    const existingSlugs = new Set(
      (await ctx.db.query("jobs").collect()).map((j) => j.slug)
    );

    let created = 0;
    let skipped = 0;

    const now = Date.now();

    for (const job of ALL_JOBS) {
      if (existingSlugs.has(job.slug)) {
        skipped++;
        continue;
      }

      const requiredProgramIds = job.requiredPlan && programIds[job.requiredPlan]
        ? [programIds[job.requiredPlan]]
        : [];

      await ctx.db.insert("jobs", {
        title: job.title,
        slug: job.slug,
        shortDescription: job.shortDescription,
        description: job.description,
        category: job.category,
        skills: job.skills,
        requirements: job.requirements,
        requiredProgramIds: requiredProgramIds.length > 0 ? requiredProgramIds : undefined,
        payment: job.payment,
        paymentType: job.paymentType,
        workType: job.workType,
        difficulty: job.difficulty,
        estimatedDuration: job.estimatedDuration,
        deadline: new Date(now + job.deadlineDays * 24 * 60 * 60 * 1000).toISOString(),
        openings: job.openings,
        status: "published",
        applicationQuestions: job.applicationQuestions,
        createdAt: now,
        updatedAt: now,
      });
      created++;
    }

    return { created, skipped, total: ALL_JOBS.length };
  },
});

export const countJobs = query({
  args: {},
  handler: async (ctx) => {
    const jobs = await ctx.db.query("jobs").collect();
    return { total: jobs.length };
  },
});
